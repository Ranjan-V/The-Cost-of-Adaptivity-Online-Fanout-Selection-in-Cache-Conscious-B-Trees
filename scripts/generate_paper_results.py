def summarize_shifting_latest(rows):
    indexes = []
    for row in rows:
        if row.get("index") not in indexes:
            indexes.append(row.get("index"))

    output = []
    for index in indexes:
        group = [row for row in rows if row.get("index") == index]
        operations = sum(as_int(row, "operations") for row in group)
        run_ms = sum(as_float(row, "run_ms") for row in group)
        reconfig_ms = sum(as_float(row, "reconfigure_ms") for row in group)
        output.append({
            "index": index,
            "throughput": operations / run_ms * 1000.0 if run_ms > 0 else 0.0,
            "throughput_with_reconfig": operations / (run_ms + reconfig_ms) * 1000.0
            if (run_ms + reconfig_ms) > 0 else 0.0,
            "adaptations": sum(as_int(row, "adaptations") for row in group),
            "restructures": sum(as_int(row, "restructures") for row in group),
            "p95": mean([as_float(row, "p95_us") for row in group]),
        })
    return sorted(output, key=lambda row: row["throughput"], reverse=True)


def summarize_shifting_trials(rows):
    by_trial_index = {}
    for row in rows:
        key = (row.get("trial"), row.get("index"))
        by_trial_index.setdefault(key, {
            "operations": 0,
            "run_ms": 0.0,
            "reconfigure_ms": 0.0,
            "adaptations": 0,
            "restructures": 0,
            "p95": [],
        })
        item = by_trial_index[key]
        item["operations"] += as_int(row, "operations")
        item["run_ms"] += as_float(row, "run_ms")
        item["reconfigure_ms"] += as_float(row, "reconfigure_ms")
        item["adaptations"] += as_int(row, "adaptations")
        item["restructures"] += as_int(row, "restructures")
        item["p95"].append(as_float(row, "p95_us"))

    by_index = {}
    for (_trial, index), item in by_trial_index.items():
        tput = item["operations"] / item["run_ms"] * 1000.0 if item["run_ms"] > 0 else 0.0
        tput_reconfig = item["operations"] / (
            item["run_ms"] + item["reconfigure_ms"]
        ) * 1000.0 if (item["run_ms"] + item["reconfigure_ms"]) > 0 else 0.0
        by_index.setdefault(index, {
            "throughputs": [],
            "throughputs_reconfig": [],
            "adaptations": [],
            "restructures": [],
            "p95": [],
        })
        by_index[index]["throughputs"].append(tput)
        by_index[index]["throughputs_reconfig"].append(tput_reconfig)
        by_index[index]["adaptations"].append(item["adaptations"])
        by_index[index]["restructures"].append(item["restructures"])
        by_index[index]["p95"].append(mean(item["p95"]))

    output = []
    for index, item in by_index.items():
        output.append({
            "index": index,
            "throughput": mean(item["throughputs"]),
            "ci": ci95(item["throughputs"]),
            "throughput_with_reconfig": mean(item["throughputs_reconfig"]),
            "adaptations": mean(item["adaptations"]),
            "restructures": mean(item["restructures"]),
            "p95": mean(item["p95"]),
            "trials": len(item["throughputs"]),
        })
    return sorted(output, key=lambda row: row["throughput"], reverse=True)


def summarize_overhead(rows):
    output = []
    workloads = []
    for row in rows:
        if row.get("workload") not in workloads:
            workloads.append(row.get("workload"))

    for workload in workloads:
        group = [row for row in rows if row.get("workload") == workload]
        static_base = next((row for row in group if row.get("index") == "Static B+Tree"), None)
        static_region = next((row for row in group if row.get("index") == "Static Region"), None)
        region_monitor = next((row for row in group if row.get("index") == "Static Region + Monitor"), None)
        segmented_no_records = next((row for row in group if row.get("index") == "Segmented No Records"), None)
        segmented_records = next((row for row in group if row.get("index") == "Segmented Records Only"), None)
        segmented_monitor_records = next((row for row in group if row.get("index") == "Segmented Monitor + Records"), None)
        segmented_full = next((row for row in group if row.get("index") == "Segmented Full Adaptive"), None)
        static_tput = throughput_value(static_base)
        region_tput = throughput_value(static_region)
        region_monitor_tput = throughput_value(region_monitor)
        no_records_tput = throughput_value(segmented_no_records)
        records_tput = throughput_value(segmented_records)
        monitor_records_tput = throughput_value(segmented_monitor_records)
        full_tput = throughput_value(segmented_full)
        output.append({
            "workload": workload,
            "static": static_tput,
            "region": region_tput,
            "region_monitor": region_monitor_tput,
            "region_monitor_vs_region": region_monitor_tput / region_tput
            if region_tput > 0 and region_monitor else 0.0,
            "region_vs_static": region_tput / static_tput if static_tput > 0 else 0.0,
            "segmented_no_records": no_records_tput,
            "segmented_no_records_vs_region": no_records_tput / region_tput
            if region_tput > 0 else 0.0,
            "segmented_records": records_tput,
            "segmented_records_vs_no_records": records_tput / no_records_tput
            if no_records_tput > 0 else 0.0,
            "segmented_monitor_records": monitor_records_tput,
            "segmented_monitor_records_vs_records": monitor_records_tput / records_tput
            if records_tput > 0 else 0.0,
            "segmented_full": full_tput,
            "segmented_full_vs_monitor_records": full_tput / monitor_records_tput
            if monitor_records_tput > 0 else 0.0,
            "full_ci": as_float(segmented_full, "ci95_ops_sec") if segmented_full else 0.0,
            "full_cv": as_float(segmented_full, "cv_percent") if segmented_full else 0.0,
            "trials": as_int(segmented_full, "trials") if segmented_full else 0,
            "cost_skips": metric_value(segmented_full, "skipped_cost", "mean_skipped_cost"),
            "rebuilds": metric_value(segmented_full, "restructures", "mean_restructures"),
        })
    return output


def summarize_wiki(rows):
    if not rows:
        return []

    by_index = {}
    for row in rows:
        item = by_index.setdefault(row["index"], {
            "index": row["index"],
            "trace_source": row.get("trace_source", "unknown"),
            "operations": 0,
            "run_ms": 0.0,
            "p95": [],
            "p99": [],
            "adaptations": 0,
            "restructures": 0,
        })
        item["operations"] += as_int(row, "operations")
        item["run_ms"] += as_float(row, "run_ms")
        item["p95"].append(as_float(row, "p95_us"))
        item["p99"].append(as_float(row, "p99_us"))
        item["adaptations"] += as_int(row, "adaptations")
        item["restructures"] += as_int(row, "restructures")

    output = []
    for item in by_index.values():
        output.append({
            "index": item["index"],
            "trace_source": item["trace_source"],
            "throughput": item["operations"] / item["run_ms"] * 1000.0
            if item["run_ms"] > 0 else 0.0,
            "p95": mean(item["p95"]),
            "p99": mean(item["p99"]),
            "adaptations": item["adaptations"],
            "restructures": item["restructures"],
        })
    return sorted(output, key=lambda row: row["throughput"], reverse=True)


def summarize_threads(rows):
    if not rows:
        return []
    base = as_float(rows[0], "ops_sec")
    output = []
    for row in rows:
        tput = as_float(row, "ops_sec")
        output.append({
            "threads": as_int(row, "threads"),
            "throughput": tput,
            "speedup": tput / base if base > 0 else 0.0,
            "reads": as_int(row, "reads"),
            "updates": as_int(row, "updates"),
        })
    return output


