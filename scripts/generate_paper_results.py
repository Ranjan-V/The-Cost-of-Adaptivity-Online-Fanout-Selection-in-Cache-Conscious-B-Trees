def write_latex_table(path, caption, label, columns, rows):
    with open(path, "w") as handle:
        handle.write("% Auto-generated by scripts/generate_paper_results.py\n")
        handle.write("\\begin{table}[t]\n")
        handle.write("\\centering\n")
        handle.write("\\caption{" + latex_escape(caption) + "}\n")
        handle.write("\\label{" + latex_escape(label) + "}\n")
        handle.write("\\begin{tabular}{" + ("l" * len(columns)) + "}\n")
        handle.write("\\toprule\n")
        handle.write(" & ".join(latex_escape(col) for col in columns) + " \\\\\n")
        handle.write("\\midrule\n")
        for row in rows:
            handle.write(" & ".join(latex_escape(cell) for cell in row) + " \\\\\n")
        handle.write("\\bottomrule\n")
        handle.write("\\end{tabular}\n")
        handle.write("\\end{table}\n")


def summarize_ycsb_latest(rows):
    output = []
    workloads = []
    for row in rows:
        if row.get("workload") not in workloads:
            workloads.append(row.get("workload"))

    for workload in workloads:
        group = [row for row in rows if row.get("workload") == workload]
        base = next((row for row in group if row.get("index") == "Static B+Tree f=64"), None)
        seg = next((row for row in group if row.get("index") == "Segmented Adaptive"), None)
        best = max(group, key=lambda row: as_float(row, "throughput_ops_sec"))
        base_tput = as_float(base, "throughput_ops_sec") if base else 0.0
        seg_tput = as_float(seg, "throughput_ops_sec") if seg else 0.0
        best_tput = as_float(best, "throughput_ops_sec")
        output.append({
            "workload": workload,
            "base": base_tput,
            "segmented": seg_tput,
            "segmented_vs_base": seg_tput / base_tput if base_tput > 0 else 0.0,
            "best": best.get("index", ""),
            "best_tput": best_tput,
            "best_vs_base": best_tput / base_tput if base_tput > 0 else 0.0,
        })
    return output


