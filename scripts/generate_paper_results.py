def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="") as handle:
        return list(csv.DictReader(handle))


def as_float(row, key):
    try:
        return float(row[key])
    except (KeyError, ValueError):
        return 0.0


def as_int(row, key):
    try:
        return int(float(row[key]))
    except (KeyError, ValueError):
        return 0


def throughput_value(row):
    if not row:
        return 0.0
    value = as_float(row, "throughput_ops_sec")
    if value > 0.0:
        return value
    return as_float(row, "mean_ops_sec")


def metric_value(row, raw_key, mean_key):
    if not row:
        return 0.0
    value = as_float(row, raw_key)
    if value > 0.0:
        return value
    return as_float(row, mean_key)


def mean(values):
    return sum(values) / len(values) if values else 0.0


def stddev(values):
    if len(values) < 2:
        return 0.0
    avg = mean(values)
    return math.sqrt(sum((value - avg) ** 2 for value in values) / (len(values) - 1))


